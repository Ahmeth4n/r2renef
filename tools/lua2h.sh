#!/bin/sh
# Turns src/renef_java.lua into src/renef_java_lua.h (the Lua the plugin
# sends to the target, as a NUL-terminated byte array). The header is
# checked in, so this only has to run when the Lua file changes:
#   make lua-header
set -e
cd "$(dirname "$0")/.."
IN=src/renef_java.lua
OUT=src/renef_java_lua.h
{
  echo "/* Generated by tools/lua2h.sh from $IN - do not edit. */"
  echo "#ifndef RENEF_JAVA_LUA_H"
  echo "#define RENEF_JAVA_LUA_H"
  echo "static const char rn_java_lua[] = {"
  od -An -v -tx1 "$IN" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g; s/^/  /'
  echo "  0x00"
  echo "};"
  echo "#endif"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$IN" | tr -d ' ') bytes of Lua)"
